print("Processing Gemini-generated images for Home 2...")
for item in mapping:
    src_path = os.path.join(brain_dir, item["src"])
    dest_path = os.path.join(target_dir, item["dest"])
    tw, th = item["w"], item["h"]
    
    if not os.path.exists(src_path):
        print(f"Error: {src_path} does not exist!")
        continue
        
    img = Image.open(src_path)
    target_ratio = tw / th
    img_ratio = img.width / img.height
    
    if img_ratio > target_ratio:
        new_w = int(img.height * target_ratio)
        left = (img.width - new_w) // 2
        img_cropped = img.crop((left, 0, left + new_w, img.height))
    else:
        new_h = int(img.width / target_ratio)
        top = (img.height - new_h) // 2
        img_cropped = img.crop((0, top, img.width, top + new_h))
        
    final_img = img_cropped.resize((tw, th), Image.Resampling.LANCZOS)
    final_img.save(dest_path, "WEBP", quality=92, method=6)
    kb = os.path.getsize(dest_path) / 1024
    print(f"  ✓ Saved {dest_path}: {tw}x{th} ({kb:.1f} KB)")

print("\nDone! All Home 2 images generated by Gemini have been saved to assets/images/home2/.")
